"""
Restaurant AI Agent order service.
Uses Neon PostgreSQL.
Never drops, seeds, or resets existing menu_items/stock.
"""

import os
from typing import Iterable, Mapping, Any

import psycopg
from psycopg.rows import dict_row
from dotenv import load_dotenv
from pathlib import Path


load_dotenv(Path(__file__).resolve().parent / ".env")


def get_order_connection():
    database_url = os.getenv("DATABASE_URL")
    if not database_url:
        raise RuntimeError("DATABASE_URL is missing.")

    return psycopg.connect(database_url, row_factory=dict_row)


def initialize_order_tables() -> None:
    with get_order_connection() as conn:
        conn.execute("""
            CREATE TABLE IF NOT EXISTS customers (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                customer_name TEXT NOT NULL,
                phone TEXT,
                created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
            )
        """)

        conn.execute("""
            CREATE TABLE IF NOT EXISTS orders (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                customer_id BIGINT NOT NULL REFERENCES customers(id),
                status TEXT NOT NULL DEFAULT 'CONFIRMED'
                    CHECK (status IN ('PENDING','CONFIRMED','CANCELLED')),
                total_amount DOUBLE PRECISION NOT NULL DEFAULT 0
                    CHECK (total_amount >= 0),
                created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
            )
        """)

        conn.execute("""
            CREATE TABLE IF NOT EXISTS order_items (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                order_id BIGINT NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
                menu_item_id BIGINT NOT NULL REFERENCES menu_items(id),
                dish_name TEXT NOT NULL,
                quantity INTEGER NOT NULL CHECK (quantity > 0),
                unit_price DOUBLE PRECISION NOT NULL CHECK (unit_price >= 0),
                line_total DOUBLE PRECISION NOT NULL CHECK (line_total >= 0)
            )
        """)

        conn.execute("""
            CREATE INDEX IF NOT EXISTS idx_orders_customer_created
            ON orders(customer_id, created_at)
        """)

        conn.execute("""
            CREATE INDEX IF NOT EXISTS idx_order_items_order
            ON order_items(order_id)
        """)


def _normalize_items(items: Iterable[Mapping[str, Any]]) -> list[dict[str, Any]]:
    combined: dict[str, dict[str, Any]] = {}

    for item in items:
        name = str(item.get("dish_name", "")).strip()
        quantity = item.get("quantity")

        if not name:
            raise ValueError("Every item must include a dish_name.")

        if isinstance(quantity, bool) or not isinstance(quantity, int) or quantity <= 0:
            raise ValueError(f"Quantity for '{name}' must be a positive whole number.")

        key = name.casefold()
        if key not in combined:
            combined[key] = {"dish_name": name, "quantity": quantity}
        else:
            combined[key]["quantity"] += quantity

    if not combined:
        raise ValueError("Order must contain at least one item.")

    return list(combined.values())


def _menu_item_by_name(conn, name: str):
    return conn.execute("""
        SELECT id, dish_name, price, stock
        FROM menu_items
        WHERE LOWER(dish_name) = LOWER(%s)
        LIMIT 1
    """, (name.strip(),)).fetchone()


def preview_order(items: Iterable[Mapping[str, Any]]) -> dict[str, Any]:
    normalized = _normalize_items(items)
    initialize_order_tables()

    with get_order_connection() as conn:
        lines, total, can_place = [], 0.0, True

        for requested in normalized:
            row = _menu_item_by_name(conn, requested["dish_name"])

            if row is None:
                raise ValueError(f"'{requested['dish_name']}' is not available on the menu.")

            qty = requested["quantity"]
            price = float(row["price"])
            stock = int(row["stock"])
            in_stock = stock >= qty

            if not in_stock:
                can_place = False

            line_total = price * qty
            total += line_total

            lines.append({
                "menu_item_id": int(row["id"]),
                "dish_name": row["dish_name"],
                "quantity": qty,
                "unit_price": price,
                "line_total": line_total,
                "stock_available": stock,
                "in_stock": in_stock,
            })

        return {
            "can_place_order": can_place,
            "items": lines,
            "total_amount": total,
        }


def place_order(
    customer_name: str,
    items: Iterable[Mapping[str, Any]],
    phone: str | None = None,
) -> dict[str, Any]:
    name = str(customer_name or "").strip()
    if not name:
        raise ValueError("Customer name is required.")

    normalized = _normalize_items(items)
    initialize_order_tables()

    with get_order_connection() as conn:
        customer = conn.execute("""
            SELECT id FROM customers
            WHERE LOWER(customer_name) = LOWER(%s)
            ORDER BY id LIMIT 1
        """, (name,)).fetchone()

        if customer is None:
            customer = conn.execute("""
                INSERT INTO customers (customer_name, phone)
                VALUES (%s, %s)
                RETURNING id
            """, (name, phone)).fetchone()
            customer_id = int(customer["id"])
        else:
            customer_id = int(customer["id"])
            if phone:
                conn.execute(
                    "UPDATE customers SET phone = %s WHERE id = %s",
                    (phone, customer_id),
                )

        checked, total = [], 0.0

        # Lock rows in consistent ID order to reduce concurrent-order conflicts.
        for requested in sorted(normalized, key=lambda x: x["dish_name"].casefold()):
            row = conn.execute("""
                SELECT id, dish_name, price, stock
                FROM menu_items
                WHERE LOWER(dish_name) = LOWER(%s)
                LIMIT 1
                FOR UPDATE
            """, (requested["dish_name"].strip(),)).fetchone()

            if row is None:
                raise ValueError(f"'{requested['dish_name']}' is not available on the menu.")

            qty = requested["quantity"]
            stock = int(row["stock"])

            if stock < qty:
                raise ValueError(
                    f"Not enough stock for {row['dish_name']}: requested {qty}, available {stock}."
                )

            price = float(row["price"])
            line_total = price * qty
            checked.append({
                "menu_item_id": int(row["id"]),
                "dish_name": row["dish_name"],
                "quantity": qty,
                "unit_price": price,
                "line_total": line_total,
            })
            total += line_total

        order = conn.execute("""
            INSERT INTO orders (customer_id, status, total_amount)
            VALUES (%s, 'CONFIRMED', %s)
            RETURNING id
        """, (customer_id, total)).fetchone()

        order_id = int(order["id"])

        for item in checked:
            updated = conn.execute("""
                UPDATE menu_items
                SET stock = stock - %s
                WHERE id = %s AND stock >= %s
            """, (item["quantity"], item["menu_item_id"], item["quantity"]))

            if updated.rowcount != 1:
                raise ValueError(f"Stock changed for {item['dish_name']}; please try again.")

            conn.execute("""
                INSERT INTO order_items
                (order_id, menu_item_id, dish_name, quantity, unit_price, line_total)
                VALUES (%s, %s, %s, %s, %s, %s)
            """, (
                order_id, item["menu_item_id"], item["dish_name"],
                item["quantity"], item["unit_price"], item["line_total"],
            ))

    result = get_order_by_id(order_id)
    if result is None:
        raise RuntimeError("Order was saved but could not be retrieved.")
    return result


def _order_with_items(conn, row) -> dict[str, Any]:
    items = conn.execute("""
        SELECT menu_item_id, dish_name, quantity, unit_price, line_total
        FROM order_items WHERE order_id = %s ORDER BY id
    """, (row["id"],)).fetchall()

    return {
        "order_id": int(row["id"]),
        "customer_id": int(row["customer_id"]),
        "customer_name": row["customer_name"],
        "phone": row["phone"],
        "status": row["status"],
        "total_amount": float(row["total_amount"]),
        "created_at": row["created_at"].isoformat(),
        "items": [{
            "menu_item_id": int(item["menu_item_id"]),
            "dish_name": item["dish_name"],
            "quantity": int(item["quantity"]),
            "unit_price": float(item["unit_price"]),
            "line_total": float(item["line_total"]),
        } for item in items],
    }


def get_order_by_id(order_id: int) -> dict[str, Any] | None:
    initialize_order_tables()

    with get_order_connection() as conn:
        row = conn.execute("""
            SELECT o.id, o.customer_id, c.customer_name, c.phone,
                   o.status, o.total_amount, o.created_at
            FROM orders o JOIN customers c ON c.id = o.customer_id
            WHERE o.id = %s
        """, (int(order_id),)).fetchone()

        return None if row is None else _order_with_items(conn, row)


def get_order_history(limit: int = 20) -> list[dict[str, Any]]:
    if isinstance(limit, bool) or not isinstance(limit, int) or limit <= 0:
        raise ValueError("limit must be a positive integer.")

    initialize_order_tables()

    with get_order_connection() as conn:
        rows = conn.execute("""
            SELECT o.id, o.customer_id, c.customer_name, c.phone,
                   o.status, o.total_amount, o.created_at
            FROM orders o JOIN customers c ON c.id = o.customer_id
            ORDER BY o.id DESC LIMIT %s
        """, (limit,)).fetchall()

        return [_order_with_items(conn, row) for row in rows]


def cancel_order(order_id: int, customer_name: str) -> dict[str, Any]:
    name = str(customer_name or "").strip()
    if not name:
        raise ValueError("Customer name is required.")
    if isinstance(order_id, bool) or int(order_id) <= 0:
        raise ValueError("A valid order ID is required.")

    order_id = int(order_id)
    initialize_order_tables()

    with get_order_connection() as conn:
        row = conn.execute("""
            SELECT o.id, o.customer_id, c.customer_name, c.phone,
                   o.status, o.total_amount, o.created_at
            FROM orders o JOIN customers c ON c.id = o.customer_id
            WHERE o.id = %s
            FOR UPDATE OF o
        """, (order_id,)).fetchone()

        if row is None:
            raise ValueError(f"Order #{order_id} was not found.")
        if row["customer_name"].strip().casefold() != name.casefold():
            raise ValueError(f"Order #{order_id} does not belong to customer '{name}'.")
        if row["status"] == "CANCELLED":
            raise ValueError(f"Order #{order_id} has already been cancelled.")
        if row["status"] not in ("PENDING", "CONFIRMED"):
            raise ValueError(f"Order #{order_id} cannot be cancelled (status: {row['status']}).")

        items = conn.execute("""
            SELECT menu_item_id, dish_name, quantity
            FROM order_items WHERE order_id = %s
            ORDER BY menu_item_id
        """, (order_id,)).fetchall()

        for item in items:
            updated = conn.execute("""
                UPDATE menu_items SET stock = stock + %s
                WHERE id = %s
            """, (int(item["quantity"]), int(item["menu_item_id"])))

            if updated.rowcount != 1:
                raise ValueError(f"Could not restore stock for {item['dish_name']}.")

        updated = conn.execute("""
            UPDATE orders SET status = 'CANCELLED'
            WHERE id = %s AND status IN ('PENDING', 'CONFIRMED')
        """, (order_id,))

        if updated.rowcount != 1:
            raise ValueError(f"Order #{order_id} could not be cancelled.")

    result = get_order_by_id(order_id)
    if result is None:
        raise RuntimeError("Order was cancelled but could not be retrieved.")
    return result


initialize_order_tables()